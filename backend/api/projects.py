"""
Project API endpoints.
Handles all CRUD operations for projects.
"""

from flask import Blueprint, jsonify, request
import db.projects

# Create blueprint
projects_bp = Blueprint('projects', __name__)


@projects_bp.route('/projects', methods=['GET'])
def get_projects():
    """
    Get all projects from the database.
    
    Returns:
        JSON response with list of projects
        
    Example:
        GET /api/projects
        Response: {"success": true, "data": [...]}
    """
    try:
        print("📥 GET /api/projects - Fetching all projects")
        result = db.projects.get_all_projects()
        
        if result['success']:
            return jsonify(result), 200
        else:
            return jsonify(result), 500
            
    except Exception as e:
        print(f"❌ Error in get_projects endpoint: {e}")
        return jsonify({
            "success": False,
            "error": "Failed to fetch projects"
        }), 500


@projects_bp.route('/projects/<project_id>', methods=['GET'])
def get_project(project_id):
    """
    Get a single project by ID with assigned employees.
    
    Args:
        project_id: Project ID from URL
        
    Returns:
        JSON response with project data
    """
    try:
        print(f"📥 GET /api/projects/{project_id} - Fetching project")
        result = db.projects.get_project_by_id(project_id)
        
        if result['success']:
            return jsonify(result), 200
        else:
            return jsonify(result), 404
            
    except Exception as e:
        print(f"❌ Error in get_project endpoint: {e}")
        return jsonify({
            "success": False,
            "error": "Failed to fetch project"
        }), 500


@projects_bp.route('/projects', methods=['POST'])
def create_project():
    """
    Create a new project.
    
    Body:
        {
            "name": "Project Name",
            "startDate": "2025-01-01",
            "endDate": "2025-03-31",
            "employeeIds": [1, 2, 3],
            "color": "#3B82F6"
        }
        
    Returns:
        JSON response with created project
    """
    try:
        print("📥 POST /api/projects - Creating project")
        data = request.get_json()
        
        if not data or not data.get('name'):
            return jsonify({
                "success": False,
                "error": "Project name is required"
            }), 400
        
        # Prepare project data (ID will be generated by db.projects.create_project)
        # Accept both 'employeeIds' and 'assignedEmployees' from frontend
        employee_ids = data.get('employeeIds') or data.get('assignedEmployees', [])
        project_data = {
            'name': data['name'],
            'description': data.get('description', ''),
            'startDate': data.get('startDate', ''),
            'endDate': data.get('endDate', ''),
            'color': data.get('color', '#3B82F6'),
            'assignedEmployees': employee_ids
        }
        
        result = db.projects.create_project(project_data)
        
        if result['success']:
            print(f"✅ Project created: {result['data']['id']}")
            return jsonify(result), 201
        else:
            return jsonify(result), 500
            
    except Exception as e:
        print(f"❌ Error in create_project endpoint: {e}")
        return jsonify({
            "success": False,
            "error": "Failed to create project"
        }), 500


@projects_bp.route('/projects/<project_id>', methods=['PUT'])
def update_project(project_id):
    """
    Update an existing project.
    
    Args:
        project_id: Project ID from URL
        
    Body:
        {
            "name": "Updated Name",
            "startDate": "2025-01-01",
            "endDate": "2025-03-31",
            "employeeIds": [1, 2],
            "color": "#3B82F6"
        }
        
    Returns:
        JSON response with updated project
    """
    try:
        print(f"📥 PUT /api/projects/{project_id} - Updating project")
        data = request.get_json()
        
        if not data:
            return jsonify({
                "success": False,
                "error": "Request body is required"
            }), 400
        
        result = db.projects.update_project(project_id, data)
        
        if result['success']:
            return jsonify(result), 200
        else:
            return jsonify(result), 500
            
    except Exception as e:
        print(f"❌ Error in update_project endpoint: {e}")
        return jsonify({
            "success": False,
            "error": "Failed to update project"
        }), 500


@projects_bp.route('/projects/<project_id>', methods=['DELETE'])
def delete_project(project_id):
    """
    Delete a project and all its tasks.
    
    Args:
        project_id: Project ID from URL
        
    Returns:
        JSON response with success message
    """
    try:
        print(f"📥 DELETE /api/projects/{project_id} - Deleting project")
        result = db.projects.delete_project(project_id)
        
        if result['success']:
            return jsonify(result), 200
        elif result.get('not_found'):
            return jsonify(result), 404
        else:
            return jsonify(result), 500
            
    except Exception as e:
        print(f"❌ Error in delete_project endpoint: {e}")
        return jsonify({
            "success": False,
            "error": "Failed to delete project"
        }), 500
